import { readFile, readdir, rm, mkdir, writeFile } from 'node:fs/promises'
import { spawn } from 'node:child_process'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const SRC_TTF = join(ROOT, 'public', 'fonts', 'MiSans VF.ttf')
const OUT_LATIN = join(ROOT, 'public', 'fonts', 'MiSans-VF-latin-subset.woff2')
const OUT_CJK = join(ROOT, 'public', 'fonts', 'MiSans-VF-cjk-subset.woff2')
const TMP_DIR = join(ROOT, 'node_modules', '.subset-cache')
const TEXT_FILE = join(TMP_DIR, 'chars.txt')
const FONTS_CSS = join(ROOT, 'src', 'styles', 'fonts.css')

// ── 1. 收集项目实际用到的字符 ──────────────────────────────────────────
const SCAN_EXTS = ['.md', '.mdx', '.astro', '.svelte', '.ts', '.js']
const SKIP_DIRS = new Set(['node_modules', 'dist', '.astro', 'assets'])

const chars = new Set()

// 基础字符：始终包含
for (let cp = 0x20; cp <= 0x7e; cp++) chars.add(cp)
chars.add(0x0a)
;[
  0x2013, 0x2014, // – —
  0x2018, 0x2019, 0x201c, 0x201d, 0x2026, // 弯引号、省略号
  0x00a9, 0x2122, // © ™
  0x3000, 0x3001, 0x3002, // 　、。
  0x300a, 0x300b, 0x300c, 0x300d, 0x300e, 0x300f, 0x3010, 0x3011, // 《》「」『』【】
  0xff01, 0xff08, 0xff09, 0xff0c, 0xff1a, 0xff1b, 0xff1f, // ！（） ， ： ； ？
].forEach((cp) => chars.add(cp))

async function scanDir(dir) {
  let entries
  try {
    entries = await readdir(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) await scanDir(join(dir, entry.name))
      continue
    }
    if (!SCAN_EXTS.some((ext) => entry.name.endsWith(ext))) continue
    const content = await readFile(join(dir, entry.name), 'utf8').catch(() => '')
    for (const ch of content) {
      const cp = ch.codePointAt(0)
      if (cp > 0x1f) chars.add(cp)
    }
  }
}

console.log('Scanning source files for used characters...')
await scanDir(join(ROOT, 'src'))

// ── 2. 按 unicode 分区拆成拉丁 / CJK 两个子集 ───────────────────────────
// 拉丁块包含 ASCII、常见符号、中文标点与全角字符；CJK 块包含汉字、假名与 emoji。
// 这样纯英文页面只会下载约 25KB 的拉丁块，中文页面才需要加载 CJK 块。
const isLatin = (cp) =>
  cp <= 0x2e7f
  || (cp >= 0x3000 && cp <= 0x303f)
  || (cp >= 0xff00 && cp <= 0xffef)

const codepoints = [...chars].sort((a, b) => a - b)
const latinChars = codepoints.filter(isLatin)
const cjkChars = codepoints.filter((cp) => !isLatin(cp))

console.log(
  `Collected ${codepoints.length} codepoints (latin ${latinChars.length}, cjk ${cjkChars.length}).`,
)

await rm(TMP_DIR, { recursive: true, force: true })
await mkdir(TMP_DIR, { recursive: true })

async function subset(codepoints, outPath) {
  await writeFile(
    TEXT_FILE,
    codepoints.map((cp) => String.fromCodePoint(cp)).join(''),
    'utf8',
  )

  await new Promise((resolve, reject) => {
    const args = [
      SRC_TTF,
      `--text-file=${TEXT_FILE}`,
      `--output-file=${outPath}`,
      '--flavor=woff2',
      '--no-hinting',
      '--desubroutinize',
    ]
    const proc = spawn('pyftsubset', args, { stdio: 'inherit' })
    proc.on('error', reject)
    proc.on('close', (code) =>
      code === 0 ? resolve() : reject(new Error(`pyftsubset exited with code ${code}`)),
    )
  })
}

console.log('Subsetting...')
await subset(latinChars, OUT_LATIN)
await subset(cjkChars, OUT_CJK)
await rm(TMP_DIR, { recursive: true, force: true })

const latinSize = (await readFile(OUT_LATIN)).length
const cjkSize = (await readFile(OUT_CJK)).length
console.log(
  `Done: latin = ${(latinSize / 1024).toFixed(0)} KB, cjk = ${(cjkSize / 1024).toFixed(0)} KB`,
)

// ── 3. 更新 fonts.css ────────────────────────────────────────────────────
const newFontFaces = `/* BEGIN:MiSans (auto-generated by scripts/subset-fonts.mjs — do not edit) */
@font-face {
  font-family: 'MiSans';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url("/fonts/MiSans-VF-latin-subset.woff2") format('woff2');
  unicode-range: U+0020-2E7F, U+3000-303F, U+FF00-FFEF;
}

@font-face {
  font-family: 'MiSans';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url("/fonts/MiSans-VF-cjk-subset.woff2") format('woff2');
  unicode-range: U+2E80-2FFF, U+3040-FEFF, U+1F000-1FFFF;
}
/* END:MiSans */`

let css = await readFile(FONTS_CSS, 'utf8')
const marker = /\/\* BEGIN:MiSans[\s\S]*?\/\* END:MiSans \*\//
css = css.replace(marker, newFontFaces)
await writeFile(FONTS_CSS, css)

console.log('Updated src/styles/fonts.css with split MiSans @font-face blocks.')
